import { expect, test, type Page } from '@playwright/test'

test.use({ hasTouch: true })

const ark = 'https://ark.cn-beijing.volces.com'
const minimax = 'https://api.minimax.io'
const png = 'tests/e2e/fixtures/images/text2image-output.png'

const select = async (page: Page, testId: string, label: string | RegExp) => {
  await page.getByTestId(testId).click()
  const menu = page.locator('.n-base-select-menu:visible')
  await menu.locator('.n-base-select-option').getByText(label).click()
  await expect(menu).toHaveCount(0)
}

test('mixes providers, splits and merges parameters, and preserves input modes and model selections', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.route('**/config.js', route => route.fulfill({
    contentType: 'application/javascript', body: 'window.runtime_config={SEEDANCE_API_KEY:"fixture-ark"};',
  }))
  await page.route(/\/(?:contents\/generations\/tasks|video_generation|files\/(?:list|retrieve))(?:[/?]|$)/, route => route.abort())
  const requests: { method: string; url: string; body?: Record<string, unknown> }[] = []
  await page.route(ark + '/**', route => {
    const request = route.request()
    requests.push({ method: request.method(), url: request.url(), body: request.postDataJSON() })
    if (request.method() === 'POST') return route.fulfill({ json: { id: 'ark-test' } })
    return route.fulfill({ json: { id: 'ark-test', status: 'failed' } })
  })
  await page.route(minimax + '/**', route => {
    const request = route.request()
    requests.push({ method: request.method(), url: request.url(), body: request.postDataJSON() })
    if (request.url().endsWith('/v1/files/list')) {
      expect(request.headers().authorization).toBe('Bearer fixture-minimax')
      return route.fulfill({ json: { base_resp: { status_code: 0 }, files: [] } })
    }
    if (request.method() === 'POST') return route.fulfill({ json: { task: { id: 'mini-test' } } })
    return route.fulfill({ json: { task: { id: 'mini-test', status: 'succeeded', content: { url: 'https://video-test.invalid/h3.mp4' } } } })
  })
  await page.route('https://video-test.invalid/h3.mp4', route => route.fulfill({ status: 200, contentType: 'video/mp4', body: Buffer.alloc(0) }))
  await page.goto('/#/video/create')
  const manage = page.getByTestId('video-manage-models')
  const manager = page.getByTestId('video-model-manager')
  await manage.click()
  const add = async (name: string, intl: boolean, model?: RegExp) => {
    await page.getByTestId('add-video-model').click()
    await select(page, 'video-config-provider', intl ? /MiniMax.*(?:International|国际站|國際站)/ : /MiniMax.*(?:China|中国站|中國站)/)
    await expect(page.getByTestId('video-config-url').locator('input')).toHaveValue(intl ? minimax : 'https://api.minimax.cn')
    await expect(page.getByTestId('video-config-key-link')).toHaveAttribute('href', intl ? /^https:\/\/platform\.minimax\.io\// : /^https:\/\/platform\.minimax\.cn\//)
    await expect(page.getByTestId('video-config-model')).toContainText('MiniMax H3 Lite')
    if (model) {
      await page.getByTestId('video-config-model').click()
      const options = page.locator('.n-base-select-menu:visible .n-base-select-option')
      await expect(options).toHaveCount(3)
      await options.getByText(model).click()
    }
    await page.getByTestId('video-config-name').locator('input').fill(name)
    await page.getByTestId('video-config-key').locator('input').fill('fixture-minimax')
    await page.getByTestId('video-config-save').click()
    const row = manager.locator('[data-testid^="video-model-row-"]').filter({ hasText: name })
    await expect(row).toBeVisible()
    return row
  }
  const h3 = await add('INTL H3', true, /^MiniMax H3 ·/)
  await h3.getByRole('button', { name: /Test Connection|测试连接|測試連線/i }).click()
  await expect.poll(() => requests.map(({ method, url }) => [method, url])).toEqual([['GET', minimax + '/v1/files/list']])
  await add('CN Lite', false)
  await page.keyboard.press('Escape')
  await expect(manager).toBeHidden()

  const picker = page.getByTestId('video-model-b')
  const chooseB = async (account: string, name: string) => {
    await picker.click()
    await page.getByRole('region', { name: new RegExp(account) }).getByRole('button', { name, exact: true }).click()
  }
  await chooseB('INTL H3', 'MiniMax-H3')
  const duration = page.getByTestId('video-param-shared-duration')
  const aDuration = page.getByTestId('video-param-a-duration')
  const bDuration = page.getByTestId('video-param-b-duration')
  await expect(duration).toContainText(/Mixed values|各列取值不同|各欄數值不同/)
  await expect(aDuration).toHaveCount(0)
  await expect(bDuration).toHaveCount(0)
  await select(page, 'video-param-shared-duration', /^7\s*(s|秒)$/)
  await page.getByTestId('video-param-shared-duration-split').click()
  await expect(duration).toHaveCount(0)
  await expect(picker).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByTestId('video-param-b-resolution')).toContainText('768p')
  await expect(aDuration).toContainText(/7\s*(s|秒)/)
  await expect(bDuration).toContainText(/7\s*(s|秒)/)
  await select(page, 'video-param-b-duration', /^9\s*(s|秒)$/)
  await expect(bDuration).toContainText(/9\s*(s|秒)/)
  await expect(aDuration).toContainText(/7\s*(s|秒)/)
  await page.reload()
  await expect(picker).toContainText('INTL H3')
  await expect(bDuration).toContainText(/9\s*(s|秒)/)
  await page.getByTestId('video-param-b-duration-merge').click()
  await expect(duration).toContainText(/9\s*(s|秒)/)
  await expect(aDuration).toHaveCount(0)
  await expect(bDuration).toHaveCount(0)

  await chooseB('INTL H3', 'MiniMax-H3-Highspeed')
  await expect(picker).toContainText('MiniMax H3 Highspeed')
  await chooseB('CN Lite', 'MiniMax-H3-Lite')
  await expect(picker).toContainText('CN Lite')
  await chooseB('INTL H3', 'MiniMax-H3-Lite')
  await expect(picker).toContainText('MiniMax H3 Lite')
  await select(page, 'video-param-b-resolution', '480p')
  await page.reload()
  await expect(picker).toContainText('MiniMax H3 Lite')

  const mode = (name: string) => page.getByTestId('video-input-mode-' + name)
  const b = page.getByTestId('video-run-b')
  await page.getByTestId('video-input').locator('textarea').fill('Original sailboat')
  await page.getByTestId('video-output').locator('textarea').fill('A narrow sailboat turns.')
  await mode('frames').click()
  await expect(b).toBeDisabled()
  const first = page.getByTestId('video-first-frame-upload')
  await first.locator('input[type=file]').setInputFiles(png)
  await expect(b).toBeEnabled()
  await page.getByTestId('video-last-frame-upload').locator('input[type=file]').setInputFiles(png)
  await expect(b).toBeEnabled()
  await mode('references').click()
  await expect(page.getByTestId('video-incompatible-b')).toBeVisible()
  const referencePicker = page.getByTestId('video-reference-upload')
  await referencePicker.locator('input[type=file]').setInputFiles(Array(5).fill(png))
  await expect(page.getByTestId('video-reference-card-5')).toBeVisible()
  await expect(page.getByTestId('video-incompatible-a')).toContainText(/4/)
  await expect(page.getByTestId('video-run-a')).toBeDisabled()
  await expect(page.getByTestId('video-run-all').first()).toBeDisabled()
  await expect(b).toBeEnabled()
  await mode('text2video').click()
  await expect(first).toHaveCount(0)
  await expect(referencePicker).toHaveCount(0)
  await mode('frames').click()
  await expect(page.getByTestId('video-first-frame-preview').locator('img')).toBeVisible()
  await mode('references').click()
  await expect(page.getByTestId('video-reference-card-1')).toBeVisible()
  await mode('text2video').click()

  await page.getByTestId('video-run-all').first().click()
  const dialog = page.getByRole('alertdialog').or(page.getByRole('dialog')).last()
  await expect(dialog).toContainText(/¥[\d.]+ \+ \$[\d.]+/)
  await dialog.getByRole('button', { name: /Confirm and generate|确认并生成|確認並產生/i }).click()
  await expect.poll(() => requests.filter(request => request.method === 'POST').length).toBe(2)
  const [arkTask, h3Task] = requests.filter(request => request.method === 'POST')
  expect(arkTask.url).toContain('/contents/generations/tasks')
  expect(arkTask.body?.duration).toBe(9)
  expect(h3Task.url).toBe(minimax + '/v2/video_generation')
  expect(h3Task.body).toMatchObject({ model: 'MiniMax-H3-Lite', resolution: '480P', duration: 9 })
  expect(arkTask.body?.content).toEqual([{ type: 'text', text: 'Original sailboat' }])
  expect(h3Task.body?.content).toEqual([{ type: 'text', text: 'A narrow sailboat turns.' }])
  await expect(page.getByTestId('video-status-a')).toContainText(/Failed|失败|失敗/i, { timeout: 10000 })
  await expect(page.getByTestId('video-usage-a')).toHaveCount(0)
  const usage = page.getByTestId('video-usage-b')
  await expect(usage).toContainText('$', { timeout: 10000 })
  await expect(usage).not.toContainText(/tokens?/i)
  await usage.tap()
  const tooltip = page.locator('.n-tooltip').filter({ hasText: '$' })
  await expect(tooltip).toBeVisible()
  await usage.tap()
  await expect(tooltip).toBeHidden()
})
